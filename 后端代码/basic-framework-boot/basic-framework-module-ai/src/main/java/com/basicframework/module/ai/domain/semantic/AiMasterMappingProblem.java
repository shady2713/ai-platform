package com.basicframework.module.ai.domain.semantic;

/**
 * 映射条目的判定问题（Y02）：目录发现必须把"能不能用"与"为什么不能用"分开表达。
 *
 * <p>发现问题不等于丢弃条目：目录**照常列出**该条目并标注问题，让操作员看到"哪里冲突、哪里过期"
 * 并要求明确处理（改/停用/新建版本）；而真正的判定（{@code resolve}）在发现同样问题时直接阻断——
 * 展示与判定用同一份事实，不存在"页面看着能用、判定却取不到"的错位。
 */
public enum AiMasterMappingProblem {

    /** 无问题：判定时刻在有效期内且无冲突。 */
    NONE,

    /** 有效期不覆盖判定时刻（尚未生效或已过期）。 */
    EXPIRED,

    /** 冲突：一对多（同对象同系统同实体类型多条生效）或多对一（同源键指向多个对象）。 */
    CONFLICT
}
